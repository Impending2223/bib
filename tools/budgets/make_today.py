"""Today's receipts by source and outlays by function, fiscal 1961-1970: budgets/today.yaml, for the budget tables under
each January budget entry (tools/bib/budgets.py).

# Usage: python3 tools/budgets/make_today.py [TABLE_2_1.xlsx TABLE_3_1.xlsx]
#   Without paths, downloads OMB's Historical Tables of the fiscal 2025 budget from govinfo (BUDGET-2025-TAB; govinfo's
#   file numbers run one ahead of the table numbers: Table 2.1 is TAB-3-1, Table 3.1 is TAB-4-1). Needs the network; the
#   build does not. Never edit budgets/today.yaml by hand: change this script and rerun it.
#
#   Table 2.1, Receipts by Source: individual and corporation income taxes, social insurance and retirement receipts,
#   excise taxes, other; the total. A line OMB marks with dots (Medicare before 1966) is null. Table 3.1, Outlays by Superfunction and Function: each function's total (the same
#   totals as Table 3.2, which begins only with 1962), undistributed offsetting receipts, the total. Unified basis,
#   today's functions, millions of dollars, as OMB revises them: not comparable line by line with the budgets of the
#   1960s, and never summed with them.
"""
import io
import os
import sys
import urllib.request
import warnings

import openpyxl
import yaml

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
OUT = os.path.join(ROOT, 'budgets', 'today.yaml')
URL = 'https://www.govinfo.gov/content/pkg/BUDGET-2025-TAB/xls/BUDGET-2025-TAB-{n}.xlsx'
YEARS = range(1961, 1971)
RECEIPTS = [('Individual income taxes', 1), ('Corporation income taxes', 2),
            ('Social insurance and retirement receipts', 3), ('Excise taxes', 6), ('Other', 7)]
FUNCTIONS = ['National Defense', 'International Affairs', 'General Science, Space, and Technology', 'Energy',
             'Natural Resources and Environment', 'Agriculture', 'Commerce and Housing Credit', 'Transportation',
             'Community and Regional Development', 'Education, Training, Employment, and Social Services', 'Health',
             'Medicare', 'Income Security', 'Social Security', 'Veterans Benefits and Services',
             'Administration of Justice', 'General Government', 'Net interest', 'Undistributed offsetting receipts']


def book(arg, n):
    if arg:
        return openpyxl.load_workbook(arg, data_only=True)
    data = urllib.request.urlopen(URL.format(n=n), timeout=120).read()
    return openpyxl.load_workbook(io.BytesIO(data), data_only=True)


def num(v):
    return None if v is None or isinstance(v, str) else int(round(v))


def sentence(name):
    """OMB's title case to the series' sentence case, the proper nouns kept."""
    if name in ('Social Security', 'Medicare'):
        return name
    words = name.split()
    return ' '.join([words[0]] + [w.lower() for w in words[1:]])


def main(args):
    warnings.filterwarnings('ignore')
    r = book(args[0] if args else None, '3-1').active
    o = book(args[1] if len(args) > 1 else None, '4-1').active
    rec = {}
    for row in r.iter_rows(values_only=True):
        if row[0] is not None and str(row[0]).strip().isdigit() and int(str(row[0]).strip()) in YEARS:
            y = int(str(row[0]).strip())
            rec[y] = {'rows': [[k, num(row[i])] for k, i in RECEIPTS], 'total': num(row[8])}
    rows = list(o.iter_rows(values_only=True))
    head = next(rw for rw in rows if rw[0] == 'Superfunction and Function')
    col = {int(str(x).strip()): j for j, x in enumerate(head) if x is not None and str(x).strip().isdigit()}
    seen, out = set(), {y: {'rows': [], 'total': None} for y in YEARS}
    for rw in rows:
        name = str(rw[0]).strip() if rw[0] is not None else ''
        if name.startswith('As percentages'):
            break
        if name in FUNCTIONS and name not in seen:
            seen.add(name)
            for y in YEARS:
                out[y]['rows'].append([sentence(name), num(rw[col[y]])])
        elif name == 'Total, Federal outlays':
            for y in YEARS:
                out[y]['total'] = num(rw[col[y]])
    missing = [f for f in FUNCTIONS if f not in seen]
    if missing:
        sys.exit(f'Table 3.1: not found: {missing}')
    doc = {
        'source': {
            'receipts': {'title': 'OMB, *Historical Tables*, Table 2.1, Receipts by Source',
                         'url': URL.format(n='3-1')},
            'outlays': {'title': 'OMB, *Historical Tables*, Table 3.1, Outlays by Superfunction and Function',
                        'url': URL.format(n='4-1')},
            'edition': 'Budget of the U.S. Government, Fiscal Year 2025',
        },
        'years': {y: {'receipts': rec[y], 'outlays': out[y]} for y in YEARS},
    }
    head = ('# Generated by tools/budgets/make_today.py from OMB\'s Historical Tables (Tables 2.1 and 3.1, the fiscal 2025\n'
            '# budget\'s). Never edit: change the script and rerun it. Millions of dollars, unified basis, today\'s functions.\n')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(head + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=120))
    print(f'{OUT}: {len(YEARS)} years')


if __name__ == '__main__':
    main(sys.argv[1:])
