"""notes/state-law-sources.md from sources/state-law.yaml (called by tools/sources/make_listing.py; deterministic).

A section a State, in the register's order: each item (session laws, code, constitution, journals, attorney general's
opinions, other) with its title and the volume's own words where read, the officer, the authority (each law, and
whether it was read, and where, or only cited), what was searched where none was found, the basis, the copies with
their access as last tested, and what the series has used it for (its `cited_as` patterns and its copies' addresses
matched in the calendar, the lists and the notes; make_listing.py STYLE 2-3). Then the Check pointers in the calendar
to a State's journals, session laws or statutes, each ruled: the register item it names, or "unmatched".

STYLE
1. Generated: edit the register and rerun make_listing.py. The first line carries the register's hash.
2. Authority first, as the owner asked ("Identified authority is strongly preferred"): *read* (the law read, in the
   volume named), *cited* (the law named by the publication or a catalog, not read), *not found* (what was searched).
"""
import re

KIND_ORDER = ["session laws", "code", "constitution", "journal", "ag opinions", "other"]
KIND_LABEL = {"session laws": "Session laws", "code": "Code", "constitution": "Constitution", "journal": "Journals",
              "ag opinions": "Attorney general's opinions", "other": "Other"}
LAW_TERM = re.compile(r"\bJournals? of (the )?(Proceedings|House|Senate|Assembly)|\b(House|Senate|Assembly) Journal|"
                      r"\bthe Journals\b|(?i:session laws)|\b(Laws|Acts|Statutes) of\b|\bLaws of Fla|(?i:\bcode\b)|"
                      r"(?i:attorney general's opinion)|\bConst\.")   # capitals matter: not the *Courier-Journal*


def esc(s):
    return re.sub(r"\s+", " ", str(s or "")).replace("|", "\\|").strip()


def url_key(u):
    u = re.sub(r"#.*$", "", str(u or ""))
    u = re.sub(r"^https?://(www\.)?", "", u).rstrip("/?&")
    if "/" not in u or len(u.split("/", 1)[1]) < 6 or "hathitrust.org" in u or re.search(r"/(search|advancedsearch)", u):
        return None
    return u


def auth_class(it):
    a = it.get("authority") or []
    if any(x.get("read") for x in a):
        return "read"
    if a:
        return "cited"
    return "not found"


def access(it):
    on = it.get("online") or []
    acc = sorted({o.get("access") for o in on})
    if "open" in acc:
        return "open"
    if not on:
        return "paper only (no copy online found)"
    return "closed (" + ", ".join(a for a in acc if a) + ")"


def matchers(it):
    pats = []
    for c in it.get("cited_as") or []:
        try:
            pats.append((re.compile(c, re.I), " " in c))
        except re.error:
            pass
    for o in it.get("online") or []:
        k = url_key(o.get("url"))
        if k:
            pats.append((re.compile(re.escape(k), re.I), False))
    return pats


def render(law, h, units, check_spans, NAMES):
    items = [(e["st"], f"{e['st']}-{i + 1}", it) for e in law for i, it in enumerate(e.get("items") or [])]
    M = {(st, n): matchers(it) for st, n, it in items}
    uses, pointers = {}, []
    for kind, uid, sts, text, f in units():
        spans = check_spans(text)
        hits = set()
        for (st, n), pats in M.items():
            for rx, needs_state in pats:
                if needs_state and st not in sts:
                    continue
                for m in rx.finditer(text):
                    how = "check" if any(a <= m.start() <= b for a, b in spans) else "use"
                    hits.add((st, n, how, m.start()))
        for st, n, how, pos in hits:
            uses.setdefault((st, n), set()).add((kind, uid, how))
        if kind != "cal" or not sts:
            continue
        for a, b in spans:
            s = text[a:b + 1]
            if LAW_TERM.search(s) and not re.search(r"canvass|returns|abstract|tabulation", s, re.I):
                named = sorted({(st, n) for st, n, how, pos in hits if a <= pos <= b})
                pointers.append((uid, sts, s.strip(), named))
    L = [f"<!-- register: {h} -->",
         "# State laws and constitutions: the listing",
         "",
         "Generated by `tools/sources/make_listing.py` (`tools/sources/law_listing.py`) from `sources/state-law.yaml`",
         "(kept by hand; its header the schema). Do not edit: edit the register and rerun. For each State and D.C., 1959-69:",
         "the session laws, the code, the constitution as then in force, the journals and the attorney general's opinions;",
         "for each, the authority (the law obliging an officer to make, keep, compile or publish it), the basis of our",
         "belief that it exists, the copies and their access as last tested from this environment, and what the series",
         "has used it for.",
         "",
         "Authority: *read*, the law read in the volume named (as then in force where that volume is of the period);",
         "*cited*, a law the publication or a catalog names, not read; *not found*, with what was searched. Basis: *seen*,",
         "a copy read; *catalog*, a catalog record seen (HathiTrust's by its Bib API); *law*; *cited*; *assumed*.",
         ""]
    cnt = {}
    for st, n, it in items:
        k = (it.get("kind"), auth_class(it))
        cnt[k] = cnt.get(k, 0) + 1
    L += ["## Summary", "", f"{len(law)} jurisdictions, {len(items)} items.", "",
          "| kind | items | authority read | cited | not found | open copy |", "|---|---|---|---|---|---|"]
    for k in KIND_ORDER:
        its = [it for st, n, it in items if it.get("kind") == k]
        if not its:
            continue
        L.append(f"| {KIND_LABEL[k]} | {len(its)} | {cnt.get((k, 'read'), 0)} | {cnt.get((k, 'cited'), 0)} | "
                 f"{cnt.get((k, 'not found'), 0)} | {sum(1 for it in its if access(it) == 'open')} |")
    L += ["", f"Check pointers in the calendar to a State's laws or journals: {len(pointers)} "
          f"({sum(1 for p in pointers if p[3])} name a register item).", ""]
    for e in law:
        st = e["st"]
        L += [f"## {e.get('name') or NAMES.get(st, st)} ({st})", ""]
        if e.get("notes"):
            L += [esc(e["notes"]), ""]
        for st2, n, it in items:
            if st2 != st:
                continue
            L += [f"### {n}. {KIND_LABEL.get(it.get('kind'), it.get('kind'))}: {esc(it.get('title'))}", ""]
            for k, lab in (("form", "Title page"), ("years", "Volumes"), ("officer", "Officer"),
                           ("printed_in", "Printed in")):
                if it.get(k):
                    L.append(f"- {lab}: {esc(it[k])}")
            L.append(f"- Authority: {auth_class(it)}")
            for a in it.get("authority") or []:
                how = f"read in {esc(a['read'])}" if a.get("read") else f"cited in {esc(a.get('cited_in'))}"
                u = f" <{a['url']}>" if a.get("url") else ""
                L.append(f"  - {esc(a.get('law'))}; {how}{u}")
            if it.get("authority_searched"):
                L.append(f"  - searched: {esc(it['authority_searched'])}")
            L.append("- Basis:")
            for b in it.get("basis") or []:
                u = f" <{b['url']}>" if b.get("url") else ""
                L.append(f"  - *{b.get('ground')}*: {esc(b.get('ref'))}{u}")
            L.append(f"- Access: {access(it)}")
            for o in it.get("online") or []:
                note = f" ({esc(o.get('note'))})" if o.get("note") else ""
                L.append(f"  - {o.get('access')}, checked {o.get('checked')}: {esc(o.get('host'))}, "
                         f"{esc(o.get('years'))}: <{o.get('url')}>{note}")
            us = uses.get((st, n), set())
            used = sorted({(k, i) for k, i, how in us if how == "use"})
            chk = sorted({(k, i) for k, i, how in us if how == "check"})
            L.append("- Used for: " + (fmt(used) if used else "nothing yet"))
            if chk:
                L.append("- Pointed to by a Check: " + fmt(chk))
            if it.get("notes"):
                L.append(f"- Note: {esc(it['notes'])}")
            L.append("")
        ps = [p for p in pointers if st in p[1]]
        if ps:
            L += [f"### Check pointers in {NAMES.get(st, st)}", "", "| entry | the Check | names |", "|---|---|---|"]
            for uid, sts, s, named in sorted(ps):
                nm = ", ".join(n for s2, n in named if s2 == st) or "unmatched"
                L.append(f"| `{uid}` | {esc(s)[:200]} | {nm} |")
            L.append("")
    return "\n".join(L).rstrip() + "\n"


def fmt(pairs):
    by = {}
    for k, i in pairs:
        by.setdefault(k, []).append(i)
    lab = {"cal": "Cal.", "list": "lists", "note": "notes"}
    return "; ".join(f"{lab.get(k, k)}: " + ", ".join(f"`{i}`" for i in sorted(v)) for k, v in sorted(by.items()))
