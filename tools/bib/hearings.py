_C = {}


def esc(t):
    return str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def load():
    """[hearing], as the generated file holds them."""
    if "rows" not in _C:
        _C["rows"] = (store.load_yaml(PATH) or {}).get("hearings", []) if os.path.exists(PATH) else []
    return _C["rows"]


def by_package():
    if "pkg" not in _C:
        _C["pkg"] = {h["package"]: h for h in load()}
    return _C["pkg"]


def hand():
    if "hand" not in _C:
        _C["hand"] = (store.load_yaml(HAND) or {}) if os.path.exists(HAND) else {}
    return _C["hand"]


def hand_rows():
    return hand().get("matches") or []


def hand_open():
    return hand().get("open") or []


def fmt_day(d, year=True):
    y, m, dd = d[:4], int(d[5:7]), int(d[8:10])
    return f"{MONTHS[m - 1]} {dd}, {y}" if year else f"{MONTHS[m - 1]} {dd}"


def days_html(days):
    """'Mar. 10, 11, 14, 1961'; across months 'Mar. 30, Apr. 6, 1961'; across years each with its year."""
    out, prev = [], None
    for i, d in enumerate(days):
        nxt = days[i + 1] if i + 1 < len(days) else None
        same_year_next = nxt and nxt[:4] == d[:4]
        if prev and prev[:7] == d[:7]:
            t = str(int(d[8:10]))
        else:
            t = fmt_day(d, year=False)
        out.append(t + ("" if same_year_next else ", " + d[:4]))
        prev = d
    return ", ".join(out).replace(", , ", ", ")


def short_title(t):
    """The title to the colon before 'hearing(s) before' (STYLE 1)."""
    t = re.split(r"(?::|[.,](?=\s*Hearings?\b))\s*(?:joint\s+)?(?:hearings?|executive session)\b", t, 1, flags=re.I)[0]
    t = t.strip(" :")
    return t if re.search(r"\b(?:Jr|Sr|[A-Z])\.$", t) else t.rstrip(" .")


SMALL = {"a", "an", "the", "and", "but", "or", "nor", "for", "so", "yet", "at", "by", "in", "of", "on", "to", "up",
         "as", "from", "into", "with", "over", "upon", "onto", "per", "via", "off", "out", "than", "vice", "e.g.", "v."}


def title_case(t):
    """The Bluebook's capitals (rule 8): every word but articles, conjunctions and prepositions of four letters or
    fewer, unless first, or after a colon or a dash; a word already capitalized, or with capitals inside it, as
    printed."""
    out, first = [], True
    for w in re.split(r"(\s+|--|—|-)", t):
        if not w or w.isspace() or w in ("--", "—", "-"):
            out.append(w)
            if w in ("--", "—"):
                first = True
            continue
        bare = w.lower().strip(",.;:()[]")
        if w[:1].islower() and not (bare in SMALL and not first) and not re.search(r"[A-Z]", w):
            w = w[:1].upper() + w[1:]
        out.append(w)
        first = w.endswith(":")
    return "".join(out).replace("--", "—")


def committee_short(c):
    """'Committee on Armed Services' -> 'S. Comm. on Armed Services' (the Bluebook's T6 abbreviations)."""
    return re.sub(r"^Committee\b", "Comm.", c or "")


def ordinal(n):
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'd', 3: 'd'}.get(n % 10, 'th')}"


def before(h):
    """'the S. Comm. on Armed Services'; 'a Subcomm. of the S. Comm. on the Judiciary': the title's own 'before ...',
    to ', United States Senate', in the Bluebook's abbreviations (T6: Committee, Subcommittee), the chamber's
    initial before the committee's name."""
    ch = {"S": "S.", "H": "H.", "J": "J."}.get(h.get("chamber"), "S.")
    m = re.search(r"\bhearings?\s+before\s+(?:the\s+)?(.+?)(?:,\s*(?:United States?|U\.\s?S\.)\s+(?:Senate|House|Congress)|,\s*"
                  r"(?:Eighty|Ninety)|,\s*\d|\.|$)", h["title"], re.I)
    t = m.group(1).strip() if m else ""
    if not t or not re.search(r"Committee", t, re.I):
        return f"the {ch} {committee_short(h.get('committee'))}"
    t = re.sub(r"\bSubcommittee\b", "Subcomm.", t, flags=re.I)
    t = re.sub(r"\bCommittee\b", "Comm.", t, flags=re.I)
    t = re.sub(r"(?:(?<=\bthe )|^)Comm\.", f"{ch} Comm.", t, count=1)
    if not t.startswith(("a ", "A ", "the ", "The ")):
        t = "the " + t
    t = title_case(t)
    return t[0].lower() + t[1:] if t[:2] in ("A ", "Th") else t


def cite(h):
    """The Bluebook's form for the hearing (STYLE 3), linked: '*Nomination of Robert S. McNamara: Hearing Before the S.
    Comm. on Armed Services*, 87th Cong. (1961)'; a part, 'pt. 1' after the title; the years held."""
    head = short_title(h["title"])
    part = re.search(r"[.,]?\s*Part\s+(\d+)$", head, re.I)
    if part:
        head = head[:part.start()]
    head = title_case(head)
    word = "Hearings" if len(h.get("held") or []) > 1 or re.search(r"\bhearings\b", h["title"], re.I) else "Hearing"
    t = f"*{head}{', pt. ' + part.group(1) if part else ''}: {word} Before {before(h)}*"
    days = h.get("held") or [h.get("issued", "")]
    y0, y1 = days[0][:4], days[-1][:4]
    year = y0 if y0 == y1 else f"{y0}–{y1[2:]}"
    return f"[{t}, {ordinal(int(h['congress']))} Cong. ({year})]({DETAILS}{h['package']})"


# ---------------------------------------------------------------- who is whom

def words(t):
    """The telling words of an office, a plural as its singular ('Justices', 'Members')."""
    from . import lives
    out = set()
    for w in re.findall(r"[a-z]{4,}", lives.fold(t or "").lower()):
        out.add(w[:-3] + "y" if w.endswith("ies") and len(w) > 5 else w[:-1] if w.endswith("s") and not
                w.endswith(("ss", "us", "is")) and len(w) > 4 else w)
    return out - lives.STOP - TELL_STOP - {"commissioner", "member", "secretary", "administrator", "representative"}


def window(h, day):
    """RULES 2: how far the hearing's first day is from the holder's nomination, where it falls in his span (else
    None). A date the roster gives by year or month alone counts from its first day (a start) or to its last (an end)."""
    import datetime
    from . import executive as X

    def d(v, end=False):
        v = (X.hi if end else X.lo)(str(v)[:10]).replace("-00", "-01")
        y, m, dd = (int(x) for x in v.split("-"))
        if end and dd == 99:
            m = 12 if m == 99 else m
            dd = (datetime.date(y + (m == 12), m % 12 + 1, 1) - datetime.timedelta(days=1)).day
        return datetime.date(y, min(m, 12), min(dd, 31))
    start = h.get("nominated") or h.get("recess") or h.get("from")
    end = h.get("confirmed") or h.get("from")
    try:
        s, e, x = d(start), d(end, True), datetime.date.fromisoformat(day)
        if h.get("from") and d(h["from"]) < s:      # in office before his nomination (a recess or acting start)
            s = d(h["from"])
    except (ValueError, TypeError):
        return None
    if (s - x).days <= 150 and (x - e).days <= 60:
        return abs((x - s).days)
    try:                                 # a sitting holder renominated (a commission's new term): in his tenure
        t = d(h.get("to") or "9999-12-31", True)
    except ValueError:
        return None
    return 10000 + (x - s).days if s <= x <= t else None


def nominee_parts(n):
    sfx = n.get("suffix") or ""
    return n.get("surname") or "", n.get("given") or "", sfx


def match_one(series, h, n):
    """(person or None, how, holder or None): RULES 1-4. how: 'hand', 'roster', 'name', or the reason none."""
    from . import lives
    from . import executive as X
    for r in hand_rows():
        if r.get("package") == h["package"] and r.get("name") == n["name"]:
            return r.get("person"), "hand", None
    sur, given, sfx = nominee_parts(n)
    if not sur or not given:
        return None, "no name to read", None
    day = (h.get("held") or [h.get("issued")])[0]
    want = words(n.get("office"))
    if not want:                         # 'Under Secretary', 'Chairman': the title's words, less the nominees' names
        want = words(h["title"]) - words(" ".join(x["name"] for x in h.get("nominees") or []))
        want -= {"hearing", "hearings", "before", "congress", "session", "senate", "first", "second", "eighty",
                 "ninety", "seventh", "eighth", "ninth", "third", "fourth", "fifth", "sixth"}
    if re.search(r"\bVice President of the United States\b", n.get("office") or ""):
        want.add("@president")
    want |= {ALIAS[w] for w in want if w in ALIAS}
    best = None
    for u, o, hd in lives.holders_of(sur):
        if hd.get("acting"):                 # an acting officer is not the nominee
            continue
        hs, hg = lives.split_name(hd["name"])
        if not lives.same_person(hs, hg, sur, given):
            continue
        hsfx = lives.suffix(hd["name"])
        if sfx and hsfx and sfx.rstrip(".") != hsfx:
            continue
        have = words(f"{X.title_at(o, hd['from'])} {hd.get('title') or ''} {X.name_at(u, hd['from'])} {o.get('id')}")
        have |= {ALIAS[w] for w in have if w in ALIAS}
        k = window(hd, day)
        own = words(f"{X.title_at(o, hd['from'])} {hd.get('title') or ''}")
        if k is None or not (want & have or not n.get("office") and k < 10000):
            continue
        # a sitting holder's tenure only for his own office renewed: a reappointment, or the office's own words
        if k >= 10000 and not (want & own or not own or re.search(r"reappoint", n.get("office") or "", re.I)):
            continue
        chair = bool(re.search(r"\bChairman\b", n.get("office") or "")) != bool(
            re.search(r"\bChairman\b", f"{X.title_at(o, hd['from'])} {hd.get('title') or ''}"))
        # the office's own words, a chairman for a chairman, the unit's words, the fewest words not asked, the dates
        senate = not (hd.get("nominated") or hd.get("confirmed") or hd.get("recess"))
        rank = (chair, senate, -len(want & own), k >= 10000, -len(want & have), k, len(have - want))
        if best is None or rank < best[0]:
            best = (rank, u, o, hd)
    if best:
        _, u, o, hd = best
        p = holder_person(series, hd["name"])
        if p:
            return p, "roster", (u["unit"], o.get("id"), hd["name"], str(hd.get("from")))
    full = f"{sur}, {given}" + (f", {sfx}." if sfx in ("Jr", "Sr") else f", {sfx}" if sfx else "")
    p = lives.person_named(series, full)
    if not p:
        return None, "no name entry fits", None
    pp = next((x for x in lives.everyone(series) if x["name"] == p), None)
    names = (pp or {}).get("names") or {p}
    roles = lives.part3_roles(series, names)
    have = lives.person_words(*lives.split_name(p), names=names, roles=roles)
    for u, o, hd in lives.holders_of(lives.split_name(p)[0]):      # the units of his offices too
        if hd["name"] in names:
            have |= words(X.name_at(u, hd["from"]))
    e = lives.bd_entry(*lives.split_name(p), member=False)
    if e:
        have |= words(e.get("text", "")[:400])
    if want & have:
        return p, "name", None
    return None, f"name only: {p} (no office word shared)", None


def holder_person(series, name):
    from . import lives
    if "hp" not in _C:
        idx = {}
        for p in lives.everyone(series):
            for nm in p.get("names") or ():
                idx.setdefault(nm, p["name"])
            idx.setdefault(p["name"], p["name"])
        _C["hp"] = idx
    return _C["hp"].get(name)


def matches(series):
    """[(hearing, nominee, person or None, how, holder)] for every nominee of every hearing."""
    if "m" not in _C:
        out = []
        for h in load():
            for n in h.get("nominees") or []:
                p, how, hd = match_one(series, h, n)
                out.append((h, n, p, how, hd))
        _C["m"] = out
    return _C["m"]


def by_person(series):
    if "bp" not in _C:
        out = {}
        for h, n, p, how, hd in matches(series):
            if p:
                out.setdefault(p, []).append((h, n))
        for p in out:
            out[p].sort(key=lambda x: ((x[0].get("held") or [x[0].get("issued")])[0], x[0]["package"]))
        _C["bp"] = out
    return _C["bp"]


def by_holder(series):
    """{(unit, office id, holder name, from): [package]}: the holders rule 2 finds (STYLE 2)."""
    out = {}
    for h, n, p, how, hd in matches(series):
        if hd:
            out.setdefault(hd, []).append(h["package"])
    return out


# ---------------------------------------------------------------- Names (STYLE 1)

def person_items(series, name, site=""):
    items = []
    for h, n in by_person(series).get(name, []):
        held = h.get("held") or []
        days = days_html(held) if held else esc(h.get("issued", ""))
        if held and CAL_FROM <= held[0] <= CAL_TO:
            first = fmt_day(held[0], year=len(held) == 1)
            days = f'<a href="{esc(site)}cal.html#d{held[0]}">{esc(first)}</a>' + esc(days[len(first):])
        else:
            days = esc(days)
        title = f'<a href="{DETAILS}{esc(h["package"])}">{esc(short_title(h["title"]))}</a>'
        b = before(h)
        b = b[4:] if b.startswith("the ") else b[:1].upper() + b[1:]
        sess = {"1": "1st", "2": "2d", "3": "3d"}.get(str(h.get("session") or ""), "")
        bits = [esc(b), f"{ordinal(int(h['congress']))} Cong." + (f", {sess} sess." if sess else "")
                if h.get("congress") else ""]
        if n.get("office"):
            bits.append(esc(n["office"]))
        items.append(f'{days}: {title}. <span class="lvc">{"; ".join(x for x in bits if x).rstrip(".")}.</span>')
    return items


