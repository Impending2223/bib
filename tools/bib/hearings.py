"""The printed nomination hearings: who each nominee is, his Names entry's list, the Executive holder's source, check.

sources/nomination-hearings.yaml (generated by tools/sources/make_nomination_hearings.py; never edit): every hearing on
a nomination govinfo's Congressional Hearings collection holds, held Jan. 1, 1953-Aug. 31, 1974, its nominees as GPO's
MODS or the title name them. sources/nomination-hearing-matches.yaml (kept by hand): what the rules below cannot
settle, a row a nominee, {package, name, person, why}: `person` the name entry's name, or null for none in the series;
and `open`, {package, name, why}: read and not settled, and what would settle it.

RULES (who is whom)
1. The hand file first: a row for the package and the name as the file gives it decides.
2. The roster: a holder of the Executive roster whose name agrees with the nominee's (lives.same_person: the surname,
   the given names by the series' rule; a suffix written on both agrees), whose office shares a telling word with the
   office the hearing names (the office's title, the holder's title and the unit's name, against the office named, less
   the words of rank and form: Secretary, Assistant, Member, Commission ...: lives.STOP and TELL_STOP here), and whose
   tenure the hearing falls in: its first day from 150 days before his nomination (or his taking office, where the
   roster gives no nomination; the designates' hearings before an inauguration) to 60 days after his confirmation (or
   his taking office; a date the roster gives by year or month from its first or to its last day); or, for a
   sitting holder renominated (a commission's new term), within his tenure, where the hearing names a
   reappointment, or an office sharing a word with his office's own title, or his office's title is the unit's
   bare membership ("Commissioner", "Member": a commission's new term). Where the hearing names no office
   ("Nomination of William D. Ruckelshaus"), the dates alone, his nomination's window, not his tenure. A place
   under two names counts as one (ALIAS: Great Britain, the United Kingdom). He is that holder, and the person is the name entry holding the holder's name. Of several such
   holders: a chairman's office for a hearing that names a chairman, a member's for one that does not; a holder the
   roster gives a nomination or confirmation before one it gives none; the one
   whose office's own title shares the most words; a nomination's window before a sitting holder's tenure; the most
   words shared with the unit's name too; the nearest dates; the fewest words not asked for.
3. The name entry: else lives.person_named gives one person for the name, and his roles (Part III's role lines, the
   roster's offices, the Directory's description) share a telling word with the office named.
4. Else none: a person whom the name alone fits, or several, is left unmatched and listed by `./bib hearings open`
   with the reason, for the hand file; a nominee no name entry holds is none. Nothing is guessed.

STYLE
1. Names: "Nomination hearings", after "Testimony before Congress": a hearing a line, by its first day held: the days
   held ("Jan. 17, 1961"; "Mar. 10, 11, 14, 1961"), the first linked to the calendar's day where the calendar holds it;
   the title as printed, to the colon before "hearing(s) before", linked to govinfo's details page; then, muted, the
   committee as the title names it, in the Bluebook's abbreviations ("S. Comm. on Armed Services"; GPO's catalogue
   gives some a later name, Banking, Housing, and Urban Affairs for Banking and Currency, or another committee), the
   Congress and session ("87th Cong., 1st sess."), and the office the hearing names where it gives one. Under the
   list, one line: its source.
2. The Executive roster: the holder rule 2 finds carries `Hearing CHRG-...` in his `src` (written once, Nov. 5, 2026,
   from the matches; a later match: `check` warns [hearings] until it is written), shown in his "Sources:" line as
   "Hearing, Jan. 17, 1961", linked to the details page, the title on hover (executive_sources).
3. The calendar: an entry on the nomination cites the hearing as its primary record, in the Bluebook's form:
   '*Nomination of Robert S. McNamara: Hearing Before the S. Comm. on Armed Services*, 87th Cong. (1961)', linked to
   the details page (`cite()` writes it).
4. check [hearings]: fails on a hearing without its package, title, link or a day; on a hand row whose package or
   name the file does not hold, or whose person names no one; on a `Hearing` source naming no package. Warns on a
   holder rule 2 matches whose `src` lacks his hearing.
"""
