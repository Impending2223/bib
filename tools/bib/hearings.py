def src_html(pkg):
    """'Hearing, Jan. 17, 1961', linked, for a holder's `Hearing CHRG-...` source; None where no package."""
    h = by_package().get(pkg)
    if not h:
        return None
    held = h.get("held") or [h.get("issued")]
    return (f'<a href="{DETAILS}{esc(pkg)}" title="{esc(short_title(h["title"]))}">'
            f'{esc(fmt_day(held[0]))}</a>')


# ---------------------------------------------------------------- check (STYLE 4)

def problems(series):
    """[(level, where, msg)]."""
    out = []
    pk = by_package()
    for h in load():
        w = f"sources/nomination-hearings.yaml: {h.get('package')}"
        if not h.get("package") or not h.get("title") or not h.get("url"):
            out.append(("error", w, "a hearing without its package, title or link"))
        if not (h.get("held") or h.get("issued")):
            out.append(("error", w, "a hearing without a day"))
    lives_names = None
    for r in hand_rows() + hand_open():
        w = f"sources/nomination-hearing-matches.yaml: {r.get('package')} {r.get('name')}"
        h = pk.get(r.get("package"))
        if not h:
            out.append(("error", w, "names no hearing in sources/nomination-hearings.yaml"))
            continue
        if r.get("name") not in [n["name"] for n in h.get("nominees") or []]:
            out.append(("error", w, "the hearing names no such nominee"))
        if r.get("person"):
            if lives_names is None:
                from . import lives
                lives_names = {p["name"] for p in lives.everyone(series)}
            if r["person"] not in lives_names:
                out.append(("error", w, f"names no person: {r['person']}"))
        if not r.get("why"):
            out.append(("error", w, "a hand row without its reason"))
    from . import executive as X
    from . import executive_sources as ES
    want = by_holder(series) if load() else {}
    for u in X.load().values():
        for o in u.get("offices") or []:
            for hd in o.get("holders") or []:
                srcs = ES.items(hd.get("src"))
                for s in srcs:
                    m = re.match(r"^Hearing (\S+)$", s)
                    if m and m.group(1) not in pk:
                        out.append(("error", f"executive/{u['_file']}: {hd['name']}", f"names no hearing: {s}"))
                for p in want.get((u["unit"], o.get("id"), hd["name"], str(hd.get("from"))), []):
                    if f"Hearing {p}" not in srcs:
                        out.append(("warn", f"executive/{u['_file']}: {hd['name']}",
                                    f"the roster's hearing {p} is not in his src"))
    return out
